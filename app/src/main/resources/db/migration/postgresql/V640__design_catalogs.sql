-- Catalogs for Design's images, wireframes and videos, as documents and
-- diagrams have had theirs.
--
-- One table per kind - image_catalog, wireframe_catalog, video_catalog - as
-- document_catalog, diagram_catalog, memory_catalog and skill_catalog are: a
-- catalog is a folder of one kind of thing, and the precedent here is a table
-- per kind, never a shared table with a kind column. What the three share is
-- behaviour, and that lives in one Kotlin class (DesignCatalogs) and one
-- GraphQL door, not in one table.
--
-- Every workspace has a default catalog of each kind, called General, so
-- nobody has to make one before they can draw, import or paste anything; it
-- cannot be deleted, and is marked by is_default rather than by its name, so it
-- can be renamed. This migration makes General for every workspace there is
-- and files every existing image, wireframe and video in it, so a list looks
-- as it did after the upgrade, with one catalog shown. A workspace made later
-- gets its General the first time its catalogs are asked for.
--
-- catalog_id is nullable, and that is what keeps this additive: an older jar
-- rolled back to writes rows without one, and a null is read as the default
-- catalog everywhere (DesignCatalogs.resolve), never as "in no catalog". So
-- ON DELETE SET NULL - which a non-empty catalog never reaches, as deleting one
-- is refused - files a row in the default rather than losing it. No CHECK
-- touches catalog_id, so SQLite's immediate check and Postgres's deferred one
-- cannot disagree about it (#169).
--
-- Pictures come from three tables - drawn in Design (design_image), by a
-- workflow's image node (execution_picture) and by a task (task_picture) - and
-- the Images page lists all three, so all three take a catalog; a draw that is
-- queued (design_image_job) carries the catalog its picture will be filed in.
--
-- Additive: new tables, nullable columns, rows.

CREATE TABLE image_catalog (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    name         VARCHAR(120) NOT NULL,
    is_default   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_image_catalog_name UNIQUE (workspace_id, name)
);

-- One default per workspace: the one nothing has to be filed in to be in.
CREATE UNIQUE INDEX uq_image_catalog_default ON image_catalog (workspace_id) WHERE is_default;
ALTER TABLE design_image ADD COLUMN catalog_id BIGINT REFERENCES image_catalog (id) ON DELETE SET NULL;
ALTER TABLE execution_picture ADD COLUMN catalog_id BIGINT REFERENCES image_catalog (id) ON DELETE SET NULL;
ALTER TABLE task_picture ADD COLUMN catalog_id BIGINT REFERENCES image_catalog (id) ON DELETE SET NULL;
ALTER TABLE design_image_job ADD COLUMN catalog_id BIGINT REFERENCES image_catalog (id) ON DELETE SET NULL;

INSERT INTO image_catalog (workspace_id, name, is_default, created_by)
SELECT id, 'General', TRUE, 'orknux' FROM workspace;
UPDATE design_image SET catalog_id = (SELECT c.id FROM image_catalog c WHERE c.workspace_id = design_image.workspace_id AND c.is_default);
UPDATE execution_picture SET catalog_id = (SELECT c.id FROM image_catalog c WHERE c.workspace_id = execution_picture.workspace_id AND c.is_default);
UPDATE task_picture SET catalog_id = (SELECT c.id FROM image_catalog c WHERE c.workspace_id = task_picture.workspace_id AND c.is_default);

