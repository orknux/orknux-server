-- A flag an agent raised on the session it was running in, through
-- flag_session: a person probing the product for a weakness, or a fault the
-- agent found in the harness or the installation's setup. Read on Admin >
-- Reports > Flags and nowhere a person without that page can reach.
--
-- One row per flag, so a session can carry several. Cleared rather than
-- deleted - by the agent through unflag_session, or by an administrator on the
-- report - so the report can show both what is open and what was dealt with,
-- and by whom. No foreign keys, as session_rating has none: a removed
-- workspace or session leaves what was flagged about it readable.
CREATE TABLE session_flag (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flagged_at    TIMESTAMPTZ   NOT NULL,
    workspace_id  BIGINT        NOT NULL,
    session_id    BIGINT        NOT NULL,
    agent_name    VARCHAR(255)  NOT NULL,
    type          VARCHAR(32)   NOT NULL,
    severity      INTEGER       NOT NULL,
    note          TEXT          NOT NULL,
    cleared_at    TIMESTAMPTZ,
    cleared_by    VARCHAR(255),
    CONSTRAINT ck_session_flag_type CHECK (type IN ('SECURITY', 'TECHNICAL_ISSUE')),
    CONSTRAINT ck_session_flag_severity CHECK (severity BETWEEN 0 AND 5)
);

CREATE INDEX idx_session_flag_flagged_at ON session_flag (flagged_at);
CREATE INDEX idx_session_flag_session ON session_flag (session_id);

-- flag_session and unflag_session are built-ins in BuiltInTools.GRANTED, on
-- for every agent already, and a new agent starts with them Always; marked
-- Always on every agent that holds them and lacks the mark, in V600's shape so
-- BasicToolsAlwaysTest reads these names after V600's. Additive.
WITH basic_name (ord, name) AS (
  VALUES
    (1, 'flag_session'),
    (2, 'unflag_session')
),
missing AS (
  SELECT a.id AS agent_id, t.ord, t.name
  FROM agent a
  CROSS JOIN basic_name t
  WHERE NOT EXISTS (SELECT 1 FROM agent_hidden_tool h WHERE h.agent_id = a.id AND h.name = t.name)
    AND NOT EXISTS (SELECT 1 FROM agent_required_tool r WHERE r.agent_id = a.id AND r.name = t.name)
)
INSERT INTO agent_required_tool (agent_id, position, name)
SELECT m.agent_id,
       coalesce((SELECT max(r.position) FROM agent_required_tool r WHERE r.agent_id = m.agent_id), -1)
         + row_number() OVER (PARTITION BY m.agent_id ORDER BY m.ord),
       m.name
FROM missing m;
