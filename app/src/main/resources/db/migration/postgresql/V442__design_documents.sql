-- Documents, written in the Design perspective beside its wireframes, filed in
-- catalogs of their own.
--
-- A document's content is the editor's own document - ProseMirror JSON, as
-- TipTap writes it - saved whole by the editor and by a model writing through
-- the orknux_* document tools; the server checks its shape on every save (see
-- DocumentContent). plain_text is a copy of its words for the search, written
-- by every save. revision counts the saves, so one made against a document
-- somebody has changed since is refused rather than written over it.
--
-- Pictures stay in the artifact store and are named in the content by artifact
-- id (DESIGN-12); design_document_image lists which, rewritten by every save.
--
-- A catalog is removed with its workspace, and a document with its catalog -
-- though the API refuses to remove a catalog that still holds any.
--
-- Additive: three new tables, and a nullable column on workspace.
CREATE TABLE document_catalog (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    name         VARCHAR(120) NOT NULL,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_document_catalog_name UNIQUE (workspace_id, name)
);

CREATE TABLE design_document (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    catalog_id   BIGINT       NOT NULL REFERENCES document_catalog (id) ON DELETE CASCADE,
    name         VARCHAR(200) NOT NULL,
    content      TEXT         NOT NULL,
    plain_text   TEXT         NOT NULL DEFAULT '',
    page_size    VARCHAR(10)  NOT NULL DEFAULT 'A4',
    orientation  VARCHAR(10)  NOT NULL DEFAULT 'PORTRAIT',
    margins      VARCHAR(10)  NOT NULL DEFAULT 'NORMAL',
    language     VARCHAR(10),
    revision     INT          NOT NULL DEFAULT 1,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by   VARCHAR(255) NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_design_document_page_size CHECK (page_size IN ('A3', 'A4', 'A5', 'LETTER', 'LEGAL')),
    CONSTRAINT ck_design_document_orientation CHECK (orientation IN ('PORTRAIT', 'LANDSCAPE')),
    CONSTRAINT ck_design_document_margins CHECK (margins IN ('NORMAL', 'NARROW', 'WIDE'))
);

CREATE INDEX idx_design_document_workspace ON design_document (workspace_id, updated_at);
CREATE INDEX idx_design_document_catalog ON design_document (catalog_id);

CREATE TABLE design_document_image (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT      NOT NULL REFERENCES design_document (id) ON DELETE CASCADE,
    artifact_id VARCHAR(64) NOT NULL
);

CREATE INDEX idx_design_document_image_document ON design_document_image (document_id);
CREATE INDEX idx_design_document_image_artifact ON design_document_image (artifact_id);

-- The page a new document starts on, per workspace; null is A4.
ALTER TABLE workspace ADD COLUMN document_page_size VARCHAR(10);
