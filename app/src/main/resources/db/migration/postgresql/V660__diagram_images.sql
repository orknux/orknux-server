-- Pictures a person puts on a diagram - a logo, a screenshot, a photo of a
-- whiteboard - kept beside it in the installation's attachment store, and a
-- box of kind image naming one by id. Their own table rather than a chat's
-- attachments, which are private to whoever uploaded them: a diagram's
-- picture is seen by everybody who sees the diagram. Gone with the diagram.
-- Additive, so rollback-floor stays.
CREATE TABLE diagram_image (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagram_id   BIGINT        NOT NULL REFERENCES diagram (id) ON DELETE CASCADE,
    workspace_id BIGINT        NOT NULL,
    filename     VARCHAR(255)  NOT NULL,
    content_type VARCHAR(100)  NOT NULL,
    size_bytes   BIGINT        NOT NULL,
    location     VARCHAR(1000) NOT NULL,
    uploaded_by  VARCHAR(255)  NOT NULL,
    uploaded_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_diagram_image_diagram ON diagram_image (diagram_id);

-- What a picture box shows: one of these by id, or an address on the web.
