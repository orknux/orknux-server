-- A deleted object, kept so it can be put back, until it is purged.
--
-- Deleting an agent, tool, function, skill, document or diagram used to remove
-- it for good: the audit log said a thing was deleted and nothing of what it
-- was. Now the delete first writes the whole object down here and then removes
-- its row as before, so the workspace's Recycle Bin can offer it back for a
-- while. A restore re-creates the object from the snapshot - with a new id,
-- because nothing referenced it (a delete is refused while anything does) - and
-- the row is purged after a retention the installation chooses
-- (RECYCLE_BIN_RETENTION_DAYS), or sooner by hand.
--
-- The same shape as component_revision, and for the same reasons: six kinds of
-- object live in six tables, so original_id points at whichever of them `kind`
-- names and cannot be a foreign key to any of them. The snapshot is the JSON
-- ComponentSnapshot writes - the same format a version is kept in - read back
-- to re-create the object. A workspace deleted takes its bin with it, which is
-- the one key here that can have a foreign key.
CREATE TABLE recycle_bin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    workspace_id BIGINT NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,

    -- AGENT, TOOL, FUNCTION, SKILL, DOCUMENT or DIAGRAM.
    kind VARCHAR(16) NOT NULL,

    -- The id the object had. For the record and for the log; a restore gives it a new one.
    original_id BIGINT NOT NULL,

    -- The catalog a document, diagram or skill was filed in, so a restore can
    -- re-file it there. Null for the kinds that have none, and fallen back to a
    -- default folder on restore when this one is gone.
    original_catalog_id BIGINT,

    -- What it was called, so the bin lists without parsing every snapshot.
    name VARCHAR(120) NOT NULL,

    deleted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_by VARCHAR(120) NOT NULL,

    snapshot TEXT NOT NULL
);

-- A workspace's bin, newest first, which is how the page reads it.
CREATE INDEX recycle_bin_workspace_idx ON recycle_bin (workspace_id, deleted_at DESC, id DESC);

-- What the retention sweep asks for: everything deleted before a date.
CREATE INDEX recycle_bin_deleted_idx ON recycle_bin (deleted_at);
