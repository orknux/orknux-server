-- Connecting the Orknux clients - the Chrome extension, Orknux for Windows, the
-- Claude Code plugin - with a one-time pairing code instead of an access token.
-- A code lives minutes and is used once; a credential opens only the client
-- doors. Both kept as SHA-256 hashes. Additive: an older jar ignores them.
CREATE TABLE client_pairing_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(120) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX ux_client_pairing_code_hash ON client_pairing_code (code_hash);

CREATE TABLE client_credential (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(120) NOT NULL,
    name VARCHAR(200) NOT NULL,
    client VARCHAR(40) NOT NULL,
    credential_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX ux_client_credential_hash ON client_credential (credential_hash);
CREATE INDEX ix_client_credential_username ON client_credential (lower(username));
