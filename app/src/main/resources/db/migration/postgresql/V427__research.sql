-- Answer > Research: a question researched by one of the workspace's own
-- workflows, and the modes that say which workflow. Issue #659.
--
-- Additive: a nullable-free column with a default, and two new tables. A jar
-- from before this ignores all three.

-- A workflow kept off the Workflows list unless "Show hidden" is ticked. The
-- research workflows are seeded hidden: they are the workspace's to edit, and a
-- list of the workflows somebody built is not the place to meet three nobody
-- did. Hidden is not disabled - a hidden workflow runs exactly as any other.
ALTER TABLE workflow ADD COLUMN hidden BOOLEAN NOT NULL DEFAULT FALSE;

-- How deep a research goes, as a workflow to run. Shallow, Medium and Deep are
-- seeded with the workspace; CUSTOM is one a person added, a name and a
-- workflow of their choosing. The workflow is held by id without a foreign
-- key: a workflow is removed from a workspace by its assignment and its
-- definition is kept, so a mode pointing at one that has gone is said on the
-- page rather than cascaded away.
CREATE TABLE research_mode (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL,
    name VARCHAR(100) NOT NULL,
    workflow_id BIGINT,
    position INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_research_mode_kind CHECK (kind IN ('SHALLOW', 'MEDIUM', 'DEEP', 'CUSTOM')),
    CONSTRAINT uk_research_mode_name UNIQUE (workspace_id, name)
);

CREATE INDEX research_mode_workspace_idx ON research_mode (workspace_id, position);

-- One research: what was asked, how, and what came of it. The run is the
-- execution module's and is held by id, as every reference across a module
-- boundary is; the mode, the model and the workflow are copied by name as
-- well, so a list of past research still says what each one was after any of
-- them is renamed or removed.
CREATE TABLE research (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    question TEXT NOT NULL,
    mode_id BIGINT,
    mode_name VARCHAR(100) NOT NULL,
    workflow_id BIGINT NOT NULL,
    workflow_name VARCHAR(255) NOT NULL,
    model_id BIGINT,
    model_name VARCHAR(255),
    language VARCHAR(16) NOT NULL,
    output_format VARCHAR(16) NOT NULL,
    -- The websites and documents included and excluded, as JSON.
    sources TEXT NOT NULL,
    status VARCHAR(16) NOT NULL,
    execution_id BIGINT,
    -- The report as the workflow wrote it, in markdown.
    result TEXT,
    -- Where the research has got to while it runs - the step, the sub-questions,
    -- what was searched - as JSON.
    progress TEXT,
    -- The sources it read, numbered as the report cites them, as JSON.
    found_sources TEXT,
    -- The file it was saved as, on the Artifacts page.
    artifact_id BIGINT,
    error TEXT,
    started_by VARCHAR(255) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    CONSTRAINT ck_research_language CHECK (language IN ('ACADEMIC', 'COLLOQUIAL', 'FORMAL')),
    CONSTRAINT ck_research_output_format CHECK (output_format IN ('PDF', 'DOCUMENT')),
    CONSTRAINT ck_research_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED', 'STOPPED'))
);

CREATE INDEX research_workspace_idx ON research (workspace_id, started_at DESC);
CREATE INDEX research_execution_idx ON research (execution_id);
