-- One row per model call made into a session: its tokens and how long it took,
-- and - where the provider reported them - the timings it measured itself.
-- llama.cpp answers a `timings` object (prompt_n, prompt_ms, prompt_per_second,
-- predicted_n, predicted_ms, predicted_per_second); nothing else this server
-- speaks to does, so those columns stay null for every other provider rather
-- than being filled with a speed worked out from wall-clock time. The session
-- page shows each call's speeds and their token-weighted average; the model's
-- page averages its newest calls. Additive: a new table.
--
-- No foreign key to llm_model: the model lives in the connection module, and a
-- removed model leaves the calls it made readable in the session it made them in.
CREATE TABLE session_model_call (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id           BIGINT           NOT NULL REFERENCES llm_session (id) ON DELETE CASCADE,
    model_id             BIGINT           NOT NULL,
    at                   TIMESTAMPTZ      NOT NULL,
    input_tokens         BIGINT           NOT NULL,
    cached_input_tokens  BIGINT           NOT NULL,
    output_tokens        BIGINT           NOT NULL,
    millis               BIGINT           NOT NULL,
    prompt_tokens        BIGINT,
    prompt_millis        DOUBLE PRECISION,
    prompt_per_second    DOUBLE PRECISION,
    generated_tokens     BIGINT,
    generated_millis     DOUBLE PRECISION,
    generated_per_second DOUBLE PRECISION
);

CREATE INDEX idx_session_model_call_session ON session_model_call (session_id, id);
CREATE INDEX idx_session_model_call_model ON session_model_call (model_id, id);
