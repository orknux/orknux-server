-- One workspace lending another one of its components: a variable catalog or a
-- model provider. The workspace it is lent to may use it - an agent there reads
-- the catalog's variables, or answers on the provider's models - and its people
-- still cannot open the workspace that lent it. Distinct from a template, which
-- is a copy: this is the one component, used from two places.
--
-- component_id names a row in the table kind says; no foreign key, since it
-- names one of two tables. Removing the component removes its shares, in the
-- code that removes it. Removing either workspace removes them here.
CREATE TABLE workspace_share (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_workspace_id    BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    grantee_workspace_id  BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    kind                  VARCHAR(32)  NOT NULL,
    component_id          BIGINT       NOT NULL,
    created_at            TIMESTAMPTZ  NOT NULL,
    created_by            VARCHAR(255) NOT NULL,
    CONSTRAINT ck_workspace_share_kind CHECK (kind IN ('VARIABLE_CATALOG', 'MODEL_PROVIDER')),
    CONSTRAINT ck_workspace_share_other CHECK (owner_workspace_id <> grantee_workspace_id),
    CONSTRAINT uq_workspace_share UNIQUE (grantee_workspace_id, kind, component_id)
);

CREATE INDEX idx_workspace_share_owner ON workspace_share (owner_workspace_id);
