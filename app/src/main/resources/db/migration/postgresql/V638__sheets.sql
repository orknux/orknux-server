-- Sheets, kept in the Design perspective beside its documents and wireframes.
--
-- One row per sheet per workspace. The workbook is one JSON document -
-- {"tabs": [{name, cells: {"A1": "what was typed"}, widths: {"A": 160}}]} -
-- rather than a table of cells, as a wireframe's drawing is one: it is saved
-- whole by the editor and by a model writing in it, read whole by both, and
-- nothing asks for one cell across sheets. It holds what was typed and never
-- what a formula came to, which the server works out when asked; see SheetEngine.
--
-- revision counts the saves, so a save made against a workbook somebody - or a
-- model - has changed since is refused rather than written over it.
--
-- Additive: a new table.
CREATE TABLE sheet (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    name         VARCHAR(200) NOT NULL,
    workbook     TEXT         NOT NULL,
    revision     INT          NOT NULL DEFAULT 1,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by   VARCHAR(255) NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_sheet_workspace ON sheet (workspace_id, updated_at);
