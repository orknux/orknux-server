-- The messages a session's model was actually sent, in the order it was sent
-- them, so the next turn can send them again exactly.
--
-- What a session put in front of a model used to be rebuilt on every turn from
-- the event log: what was said, and a block of what tools returned. Inside a
-- turn each round's request extended the last one; at the next turn the rounds
-- were gone - the assistant message carrying the calls and the reasoning, and
-- every tool result - replaced by the final answer and a recall block. A
-- provider that caches a prompt by its prefix (llama.cpp, and every hosted one
-- that bills cached input less) missed from the third message on and read the
-- whole session again on every message.
--
-- So this keeps the conversation as it was sent, one row per message, appended
-- to and never edited. A row is the message as JSON - role, content, pictures,
-- calls, the call it answers, the reasoning echoed with it - encrypted with the
-- installation key, because a call's arguments are kept here exactly as the
-- model wrote them: the event log redacts what it shows a person, and a prompt
-- replayed with `***` in it would not be the prompt that was sent.
--
-- Additive: an older jar never reads it, and a session with no rows here is
-- rebuilt from the event log as it always was.
CREATE TABLE llm_session_prompt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES llm_session (id) ON DELETE CASCADE,
    -- Which turn wrote it, counted per session.
    turn_no INTEGER NOT NULL,
    -- Whether the turn's first write put it here: what the turn was asked with,
    -- as against what it answered. A regenerate keeps the first and drops the
    -- second.
    opening BOOLEAN NOT NULL DEFAULT FALSE,
    -- The message, as JSON, in the installation's encrypted envelope.
    message TEXT NOT NULL,
    -- The newest event in the session's log when this row was written. The
    -- next turn adds what was said after it - a person's message to a task, a
    -- "carry on" - and nothing before it, which this conversation already holds.
    through_event_id BIGINT,
    -- What the message weighs, in characters of text, so the size of a session's
    -- prompt is a sum rather than a decryption of every row.
    chars INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX llm_session_prompt_session_idx ON llm_session_prompt (session_id, id);
