-- Admin > Reports > Errors: one row per thing that failed - a workflow run that
-- ended FAILED, an agent that could not answer, a model the quick chat panel
-- could not get an answer from - with what it said. Written where the failure
-- happens rather than read back out of each place's own history, so the report
-- is one query and a failure is counted once. No foreign keys, as
-- session_rating has none: a removed workspace, run or session leaves what
-- went wrong readable.
CREATE TABLE error_record (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at           TIMESTAMPTZ   NOT NULL,
    workspace_id BIGINT        NOT NULL,
    -- RUN, AGENT or MODEL; no CHECK, for the reason V104 gives.
    source       VARCHAR(16)   NOT NULL,
    -- The workflow, agent or model, by name, as it was called then.
    subject      VARCHAR(255)  NOT NULL,
    execution_id BIGINT,
    session_id   BIGINT,
    message      TEXT          NOT NULL
);

CREATE INDEX idx_error_record_at ON error_record (at);

-- The runs that already failed, so the report does not start empty.
INSERT INTO error_record (at, workspace_id, source, subject, execution_id, message)
SELECT coalesce(e.finished_at, e.started_at), e.workspace_id, 'RUN', e.workflow_name, e.id,
       coalesce(e.error, 'The run failed.')
FROM workflow_execution e
WHERE e.status = 'FAILED';
