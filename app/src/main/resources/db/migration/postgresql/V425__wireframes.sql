-- Wireframes, drawn in the Design perspective beside its images. Issue #655.
--
-- One row per wireframe per workspace. The drawing itself is one JSON document
-- - {"elements": [{id, type, x, y, w, h, text, props}, ...]} - rather than a
-- table of elements: it is saved whole by the editor and by a model drawing in
-- it, read whole by both, and nothing anywhere asks for one element across
-- wireframes. The server checks its shape on every save; see WireframeDocument.
--
-- revision counts the saves, so a save made against a drawing somebody - or a
-- model - has changed since is refused rather than written over it.
--
-- Additive: a new table.
CREATE TABLE wireframe (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    name         VARCHAR(200) NOT NULL,
    document     TEXT         NOT NULL,
    revision     INT          NOT NULL DEFAULT 1,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by   VARCHAR(255) NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_wireframe_workspace ON wireframe (workspace_id, updated_at);
