-- Diagrams, drawn in the Explore perspective beside Research: boxes and the
-- lines between them, each box with notes of its own, filed in catalogs.
--
-- Rows rather than one JSON document, unlike a wireframe: a diagram is read a
-- node at a time as often as whole - an agent searches every diagram in the
-- workspace for a word and then asks for one node's notes and its neighbours -
-- and a row per node is what makes both a query rather than a parse of every
-- diagram held. A save still writes the whole drawing; revision counts those,
-- so a save made against a diagram changed since is refused.
--
-- agent_access is what an agent may do with a diagram through the orknux_*
-- tools: READ, or CHANGE as well. New diagrams start at CHANGE.
--
-- Additive: new tables.
CREATE TABLE diagram_catalog (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    name         VARCHAR(120) NOT NULL,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_diagram_catalog_name UNIQUE (workspace_id, name)
);

CREATE TABLE diagram (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    catalog_id   BIGINT       NOT NULL REFERENCES diagram_catalog (id) ON DELETE CASCADE,
    name         VARCHAR(200) NOT NULL,
    agent_access VARCHAR(10)  NOT NULL DEFAULT 'CHANGE',
    revision     INT          NOT NULL DEFAULT 1,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by   VARCHAR(255) NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_diagram_agent_access CHECK (agent_access IN ('READ', 'CHANGE'))
);

CREATE INDEX idx_diagram_workspace ON diagram (workspace_id, updated_at);
CREATE INDEX idx_diagram_catalog ON diagram (catalog_id);

CREATE TABLE diagram_node (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagram_id BIGINT       NOT NULL REFERENCES diagram (id) ON DELETE CASCADE,
    node_key   VARCHAR(64)  NOT NULL,
    position   INT          NOT NULL,
    kind       VARCHAR(20)  NOT NULL,
    label      VARCHAR(500) NOT NULL,
    x          INT          NOT NULL,
    y          INT          NOT NULL,
    w          INT          NOT NULL,
    h          INT          NOT NULL,
    color      VARCHAR(7),
    notes      TEXT,
    parent_key VARCHAR(64),
    CONSTRAINT uq_diagram_node_key UNIQUE (diagram_id, node_key)
);

CREATE TABLE diagram_edge (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagram_id BIGINT       NOT NULL REFERENCES diagram (id) ON DELETE CASCADE,
    edge_key   VARCHAR(64)  NOT NULL,
    position   INT          NOT NULL,
    source_key VARCHAR(64)  NOT NULL,
    target_key VARCHAR(64)  NOT NULL,
    label      VARCHAR(500),
    kind       VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_diagram_edge_key UNIQUE (diagram_id, edge_key)
);
